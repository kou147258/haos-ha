def _find_pil_font(size: int):
    """Load a PIL font, preferring DejaVu then falling back to PIL default."""
    from PIL import ImageFont

    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/TTF/DejaVuSans.ttf",
        "/opt/haos_fb/fonts/NotoSansCJK-Regular.ttc",
        "/opt/haos_fb/fonts/NotoSansMono-Regular.ttf",
    ]
    for path in candidates:
        if os.path.exists(path):
            try:
                return ImageFont.truetype(path, size)
            except OSError:
                continue
    return ImageFont.load_default()


class PILFont:
    """Wrapper around PIL.ImageFont that exposes a BitmapFont-like draw()."""

    def __init__(self, size: int) -> None:
        self._font = _find_pil_font(size)
        self._size = size
        self.name = "PIL"
        self.height = size

    def text_width(self, text: str, scale: int = 1) -> int:
        from PIL import ImageFont
        try:
            return int(self._font.getlength(text)) * scale
        except AttributeError:
            w, _ = self._font.getsize(text)
            return w * scale

    def draw(self, render_fn, x: int, y: int, text: str, color, scale: int = 1) -> None:
        """Render via PIL to a temporary image, then forward lit pixels."""
        from PIL import Image, ImageDraw
        w = max(1, self.text_width(text, 1))
        h = max(1, self.height)
        img = Image.new("RGBA", (w + 2, h + 2), (0, 0, 0, 0))
        d = ImageDraw.Draw(img)
        d.text((0, 0), text, font=self._font, fill=color + (255,) if len(color) == 3 else color)
        for py in range(img.height):
            for px in range(img.width):
                if img.getpixel((px, py))[3] > 128:
                    for dy in range(scale):
                        for dx in range(scale):
                            render_fn(x + px * scale + dx, y + py * scale + dy, color)


def load_font(size: int = 16) -> FontLike:
    """Load the best available font. PIL > bitmap."""
    try:
        return PILFont(size)
    except ImportError:
        return BitmapFont()


def ensure_share_fonts(hass_share: str) -> None:
    """Drop a one-line notice into the user share if no fonts are present.

    The renderer auto-detects /share/fonts/NotoSans*.ttf at startup so users
    can drop CJK-capable Noto fonts there without rebuilding the add-on.
    """
    fonts_dir = Path(hass_share) / "fonts"
    fonts_dir.mkdir(parents=True, exist_ok=True)
    note = fonts_dir / "README.txt"
    if not note.exists():
        note.write_text(
            "Drop CJK / mono fonts (.ttf / .otf / .ttc) here.\n"
            "The renderer auto-loads the first .ttf / .ttc file in this directory.\n",
            encoding="utf-8",
        )