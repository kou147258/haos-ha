def _cjk_placeholder(ch: str) -> list[int]:
    """Return a placeholder block for a glyph we don't have."""
    return [0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F]


class BitmapFont:
    """5x7 ASCII bitmap font. Renders via pixel() calls in the renderer."""

    width = _GLYPH_WIDTH
    height = _GLYPH_HEIGHT
    name = "5x7"

    def text_width(self, text: str, scale: int = 1) -> int:
        """Return the pixel width of ``text`` at the given integer scale."""
        return len(text) * (_GLYPH_WIDTH + 1) * scale

    def draw(self, render_fn, x: int, y: int, text: str, color, scale: int = 1) -> None:
        """Draw ``text`` at ``(x, y)`` calling render_fn(x, y, color) per lit pixel.

        ``render_fn`` is invoked once per lit pixel of every glyph. Anything
        that is not a known ASCII char becomes a filled placeholder block so
        the user immediately sees what their font backend cannot render.
        """
        cx = x
        for ch in text:
            glyph = _ASCII_5X7.get(ch)
            if glyph is None:
                glyph = _cjk_placeholder(ch)
            for row in range(_GLYPH_HEIGHT):
                bits = glyph[row]
                for col in range(_GLYPH_WIDTH):
                    if bits & (1 << (_GLYPH_WIDTH - 1 - col)):
                        for dy in range(scale):
                            for dx in range(scale):
                                render_fn(cx + col * scale + dx, y + row * scale + dy, color)
            cx += (_GLYPH_WIDTH + 1) * scale


