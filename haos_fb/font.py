"""Font loading for the fb0 renderer.

Tries PIL with DejaVu Sans (Alpine package ``ttf-dejavu``) first. Falls back
to a hand-rolled 5x7 ASCII bitmap when PIL is missing — the original
haos shipped this fallback so dashboards still render when the
environment is minimal.
"""
